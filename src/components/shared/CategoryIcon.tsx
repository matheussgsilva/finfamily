export function CategoryIcon({
  name,
  className,
  size = 16,
}: {
  name?: string | null;
  className?: string;
  size?: number;
}) {
  if (!name) {
    return <MoreHorizontal className={className} size={size} />;
  }
  const Icon = iconMap[name] ?? MoreHorizontal;
  return <Icon className={className} size={size} />;
}

